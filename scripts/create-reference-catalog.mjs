// Original vector design sketches for the demo catalogue, not photographs or
// evidence of completed tailoring. No third-party/customer photos are reused.
import { mkdir, writeFile } from "node:fs/promises";
const colors = [
  ["red", "merah", "#bc3f43"],
  ["yellow", "kuning", "#e2bc49"],
  ["black", "hitam", "#353839"],
  ["white", "putih", "#f1eee6"],
];
const details = [
  ["skull", "center", "logo tengkorak di tengah"],
  ["pocket", "left", "saku di kiri pemakai"],
  ["pocket", "right", "saku di kanan pemakai"],
  ["lace", "center", "renda di tengah"],
  ["flower", "center", "motif bunga di tengah"],
];
await mkdir("public/references", { recursive: true });
const catalog = [];
for (const [color, label, fill] of colors)
  for (const kind of ["tshirt", "dress"])
    for (const [detail, position, description] of details) {
      const id = `${kind}-${color}-${detail}${position === "right" ? "-right" : ""}`;
      const outline =
        kind === "tshirt"
          ? "M116 85 L78 99 L43 162 L86 186 L108 148 L108 305 L252 305 L252 148 L274 186 L317 162 L282 99 L244 85 Q180 117 116 85Z"
          : "M135 72 L111 124 L138 155 L92 305 L268 305 L222 155 L249 124 L225 72 Q180 101 135 72Z";
      const mark =
        detail === "skull"
          ? '<g fill="#eee9de" stroke="#282828" stroke-width="2"><path d="M160 169 Q155 138 180 138 Q205 138 200 169 L194 176 L194 190 L166 190 L166 176Z"/><ellipse cx="169" cy="157" rx="6" ry="7" fill="#282828"/><ellipse cx="191" cy="157" rx="6" ry="7" fill="#282828"/><path d="M180 167 L176 174 L184 174Z" fill="#282828"/><path d="M173 180V190 M180 180V190 M187 180V190"/></g>'
          : detail === "pocket"
            ? '<path d="M207 154 L240 154 L240 184 L224 195 L207 184Z" fill="none" stroke="#f4e9d5" stroke-width="3"/>'
            : detail === "lace"
              ? '<g stroke="#fff7eb" fill="none" stroke-width="3">' +
                [155, 170, 185, 200, 215]
                  .map(
                    (y) =>
                      `<path d="M143 ${y} Q152 ${y - 10} 162 ${y} T181 ${y} T200 ${y} T219 ${y}"/>`,
                  )
                  .join("") +
                "</g>"
              : '<g fill="#f4e2ac" stroke="#7d5942" stroke-width="1">' +
                [0, 60, 120, 180, 240, 300]
                  .map(
                    (angle) =>
                      `<ellipse cx="180" cy="155" rx="7" ry="17" transform="rotate(${angle} 180 174)"/>`,
                  )
                  .join("") +
                '<circle cx="180" cy="174" r="8" fill="#9e714a"/></g>';
      const positionedMark = detail === "pocket" && position === "right" ? `<g transform="translate(360 0) scale(-1 1)">${mark}</g>` : mark;
      const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="360" height="380" viewBox="0 0 360 380"><rect width="360" height="380" fill="#f2eee5"/><path d="${outline}" fill="${fill}" stroke="#34382e" stroke-width="2"/>${positionedMark}<text x="180" y="343" text-anchor="middle" font-size="12" fill="#555" font-family="Arial">SKETSA REFERENSI • BUKAN FOTO HASIL JAHIT</text></svg>`;
      await writeFile(`public/references/${id}.svg`, svg);
      catalog.push({
        id,
        name: `${kind === "dress" ? "Gaun" : "Kaos"} ${label} — ${description}`,
        image: `/references/${id}.svg`,
        attributes: [color, kind, detail, position],
        source: "Sketsa asli Rupa untuk demonstrasi",
        kind: "illustration",
      });
    }
await writeFile(
  "src/lib/reference-catalog.ts",
  `// Generated by scripts/create-reference-catalog.mjs\nimport type { ReferenceDesign } from './model';\nexport const referenceCatalog: ReferenceDesign[] = ${JSON.stringify(catalog, null, 2)};\n`,
);
console.log(`Created ${catalog.length} original design sketches.`);
